const assert=require('node:assert/strict');
const {forecast}=require('./ui/engine.js');
const base={total:6,done:0,unit:50,start:'2026-10-19',end:'2026-10-30',schedule:{1:2,3:2},excluded:[],extras:[]};
assert.equal(forecast(base).finish,'2026-10-26');
assert.equal(forecast({...base,excluded:['2026-10-19']}).finish,'2026-10-28');
assert.equal(forecast({...base,end:'2026-10-21'}).deficit,100);
assert.equal(forecast({...base,done:6}).complete,true);
assert.equal(forecast({...base,total:3}).rows[1].credited,50);
assert.equal(forecast({...base,schedule:{}}).deficit,300);
assert.equal(forecast({...base,excluded:['2026-10-19'],extras:[{date:'2026-10-19',hours:2}]}).finish,'2026-10-26');
assert.equal(forecast({...base,start:'2026-10-19',end:'2026-10-19',total:2}).finish,'2026-10-19');
assert.equal(forecast({...base,unit:60}).finish,'2026-10-26');
const holiday={id:'1',name:'Feriado',type:'holiday',start:'2026-10-19',end:'2026-10-19'};
assert.equal(forecast(base,[holiday]).finish,'2026-10-28');
assert.equal(forecast({...base,name:'Outra disciplina'},[holiday]).finish,'2026-10-28');
assert.equal(forecast({...base,excluded:['2026-10-19']},[holiday]).finish,'2026-10-28');
assert.equal(forecast(base,[{...holiday,start:'2026-09-01',end:'2026-09-30'}]).finish,'2026-10-26');
assert.equal(forecast(base,[{...holiday,end:'2026-10-21'}]).deficit,100);
assert.equal(forecast({...base,extras:[{date:'2026-10-19',hours:2}]},[holiday]).finish,'2026-10-26');
assert.equal(forecast(base,[holiday,{...holiday,id:'2'}]).finish,'2026-10-28');
assert.equal(forecast(base,[{...holiday,start:'2026-10-01',end:'2026-10-20'}]).finish,'2026-10-28');
console.log('17 verificações de cálculo aprovadas.');
const marked={...base,completedLessons:[{day:'2026-10-19',minutes:100}]};
assert.equal(forecast(marked).done,100);
assert.equal(forecast(marked).remaining,200);
assert.equal(forecast(marked).available,300);
assert.equal(forecast(marked).finish,'2026-10-26');
assert.equal(forecast(marked).rows[0].completed,true);
assert.equal(forecast({...marked,done:2}).remaining,100);
assert.equal(forecast({...marked,done:2}).finish,'2026-10-21');
assert.equal(forecast({...marked,schedule:{1:4,3:2}}).rows[0].minutes,100);
assert.equal(forecast(marked,[holiday]).rows[0].completed,true);
assert.equal(forecast(marked,[holiday]).remaining,200);
assert.equal(forecast({...marked,excluded:['2026-10-19']}).done,100);
assert.equal(forecast({...marked,completedLessons:[]}).done,0);
assert.equal(forecast({...marked,completedLessons:[{day:'2026-10-19',minutes:100},{day:'2026-10-21',minutes:100},{day:'2026-10-26',minutes:100}]}).complete,true);
assert.equal(forecast({...marked,total:1}).done,50);
assert.equal(forecast({...marked,unit:60}).remaining,260);
assert.equal(forecast({...marked,completedLessons:[{day:'2026-10-28',minutes:100}]}).finish,'2026-10-28');
console.log('16 verificações de aulas ministradas aprovadas.');

