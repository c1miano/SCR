const assert=require('node:assert/strict');
const {collect,monthCells}=require('./ui/group-preview-model.js');
const {forecast}=require('./ui/engine.js');
const {effects}=require('./ui/professor-model.js');
const base={id:'a',name:'Disciplina A',groups:['Turma A','Turma B'],total:6,done:0,unit:50,start:'2026-10-19',end:'2026-11-30',schedule:{1:2,3:2},excluded:[],extras:[]};
const show=(c=base,month='2026-10')=>collect([c],'turma a',month,forecast);
assert.deepEqual(show().entries.map(x=>x.day),['2026-10-19','2026-10-21','2026-10-26']);
assert.equal(show().entries.at(-1).final,true);
assert.equal(show(base,'2026-11').entries.length,0);
assert.equal(show({...base,total:5}).entries.at(-1).minutes,50);
assert.equal(show({...base,total:5}).entries.at(-1).plannedMinutes,100);
assert.equal(show({...base,done:6}).entries.length,0);
assert.equal(show({...base,done:6}).completed,1);
assert.deepEqual(show({...base,completedLessons:[{day:'2026-10-19',minutes:100}]}).entries.map(x=>x.day),['2026-10-19','2026-10-21','2026-10-26']);
assert.equal(show({...base,completedLessons:[{day:'2026-10-19',minutes:300}]}).entries.length,0);
assert.equal(collect([base],'Turma B','2026-10',forecast).entries.length,3);
assert.equal(collect([base],'Turma C','2026-10',forecast).entries.length,0);
assert.equal(show({...base,groups:[' Turma A ','turma a']}).entries.length,3);
assert.equal(collect([base],'turma a','2026-10',()=>null).missingCalendar[0],base.name);
assert.equal(collect([base],'turma a','invalid',forecast).entries.length,0);
const extra={...base,id:'b',name:'Disciplina B'};assert.equal(collect([base,extra],'turma a','2026-10',forecast).entries.length,6);
const cal=[{start:'2026-10-19',end:'2026-10-19'}];assert.equal(collect([base],'turma a','2026-10',c=>forecast(c,cal)).entries[0].day,'2026-10-21');
const alternating={...base,total:8,schedule:{2:2},scheduleMode:'alternating',weekAnchor:'2026-10-19',scheduleB:{3:2},weekOverrides:[{weekStart:'2026-10-26',schedule:{2:2}}]};
assert.deepEqual(show(alternating).entries.map(x=>x.day),['2026-10-20','2026-10-27']);
assert.deepEqual(show(alternating,'2026-11').entries.map(x=>x.day),['2026-11-03','2026-11-11']);
const people=[{id:'p',name:'Professor',absences:[{start:'2026-10-19',end:'2026-10-19'}],extras:[{courseId:'a',date:'2026-10-20',hours:2,unit:50}]}];
const withProfessor={...base,professorIds:['p']};const result=collect([withProfessor],'turma a','2026-10',c=>{const e=effects(c,people);return forecast({...c,extras:e.extras},e.absences)});
assert.deepEqual(result.entries.map(x=>x.day),['2026-10-20','2026-10-21','2026-10-26']);
assert.equal(result.entries[0].extra,true);
assert.equal(monthCells('2028-02').filter(Boolean).length,29);
assert.equal(monthCells('2026-10').findIndex(Boolean),3);
assert.equal(monthCells('2026-10').filter(Boolean).length,31);
assert.equal(monthCells('2026-13').length,0);
const recorded=show({...base,completedLessons:[{day:'2026-10-19',minutes:100}]}).entries;
assert.equal(recorded[0].completed,true);
assert.equal(recorded[0].minutes,100);
assert.equal(recorded[0].final,false);
assert.equal(recorded[1].completed,false);
assert.equal(show({...base,completedLessons:[{day:'2026-10-19',minutes:100}]},'2026-11').entries.length,0);
console.log('29 verificações da prévia mensal por turma aprovadas.');
